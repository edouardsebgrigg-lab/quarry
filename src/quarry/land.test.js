const finish=(g,m)=>{for(let i=0;m.job&&i<10000;i++)tickJobs(g.ctx,.1);expect(m.job).toBeNull();};
const totals=g=>g.totals();
const conserve=(before,after,cargo={})=>{
  for(const id of Object.keys(before))expect((after[id]??0)+(cargo[id]??0),id).toBeCloseTo(before[id],2);
};
it('lists two distinct, finite neighbouring fields and denies unowned excavation without mutation',()=>{
  const g=createGame({seed:20}),south=parcelGround(g.ctx,'south'),before=south.serialize();
  expect(landParcels(g.ctx).reduce((t,p)=>t+p.area,152*152)).toBeGreaterThan(2*152*152);
  expect(g.actions.buyLand('south').ok).toBe(false);
  expect(g.actions.buyLand('unknown').ok).toBe(false);
  expect(g.actions.shovelDig({x:40,z:210}).ok).toBe(false);
  expect(g.actions.digGround({x:40,z:210,radius:2,bottomY:-5,maxVolume:10}).total).toBe(0);
  expect(g.actions.dumpGround({x:40,z:210,tonnes:{gravel:1}})).toBeUndefined();
  expect(planEarthworks(g.ctx,{mode:'level',ax:30,az:220,bx:40,bz:220,width:8}).ok).toBe(false);
  expect(g.actions.quoteBlast({patternId:'pocket',x:240,z:40}).reason).toMatch(/field you own/);
  expect(south.serialize()).toEqual(before);
  expect(surveyLand(g.ctx,'south').estimates.sand).toBeGreaterThan(surveyLand(g.ctx,'ridge').estimates.sand);
  expect(surveyLand(g.ctx,'ridge').coverDepth).toBeLessThan(surveyLand(g.ctx,'south').coverDepth);
  expect(surveyLand(g.ctx,'ridge').rockTonnes).toBeGreaterThan(0);
});
