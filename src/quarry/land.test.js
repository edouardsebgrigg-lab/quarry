it('shows unowned terrain without allowing traffic or excavation to change it; legacy saves start with no purchases',()=>{
  const g=createGame({seed:25}),world=createGroundAccess(g.ctx),south=parcelGround(g.ctx,'south');
  expect(world.inside(40,210)).toBe(true);expect(world.workable(40,210)).toBe(false);
  expect(world.heightAt(40,210)).toBe(south.heightAt(40,210));
  const before=south.serialize();world.applyTraffic({fromX:39,fromZ:210,x:40,z:210,width:2,weight:12000,heading:0,moisture:1,slip:1});
  expect(south.serialize()).toEqual(before);
  const old=structuredClone(g.snapshot());delete old.land;delete old.parcelGrounds;
  const restored=createGame({data:g.data,state:old});expect(landParcels(restored.ctx).every(p=>!p.owned)).toBe(true);
  expect(restored.state.money).toBe(g.state.money);
});
